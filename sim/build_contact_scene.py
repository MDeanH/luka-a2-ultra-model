"""Build a separate, explicitly assumed floating-base MuJoCo scene.

The checked-in fixed-base model and vendor files are never edited.  The scene
enables floor contact only; robot self-contact is deliberately disabled until
its collision geometry can be reviewed.
"""

import argparse
import hashlib
import json
from pathlib import Path
import xml.etree.ElementTree as ET


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "build/luka_as_is.xml"
OUTPUT = ROOT / "build/luka_contact_candidate.xml"
SOURCE_MANIFEST = ROOT / "SOURCE_MANIFEST.json"


def verified_source() -> bytes:
    data = SOURCE.read_bytes()
    manifest = json.loads(SOURCE_MANIFEST.read_text())
    entry = next(item for item in manifest["files"] if item["path"] == "build/luka_as_is.xml")
    if len(data) != entry["bytes"] or hashlib.sha256(data).hexdigest() != entry["sha256"]:
        raise ValueError("baseline XML differs from SOURCE_MANIFEST.json; review provenance before deriving")
    return data


def generate() -> bytes:
    root = ET.fromstring(verified_source())
    root.set("model", "luka_contact_candidate")

    collision = root.find("./default/default[@class='robot']/default[@class='collision']/geom")
    if collision is None or collision.get("contype") != "0":
        raise ValueError("unexpected baseline collision defaults")
    # Floor ↔ robot only: (1 & 1) or (2 & 2); robot ↔ robot: neither.
    collision.set("contype", "2")
    collision.set("conaffinity", "1")

    world = root.find("worldbody")
    if world is None:
        raise ValueError("baseline has no worldbody")
    base = world.find("body[@name='base_link']")
    if base is None or base.find("freejoint") is not None:
        raise ValueError("expected one fixed base_link")
    base.insert(0, ET.Element("freejoint", {"name": "root_free"}))
    world.insert(0, ET.Element("geom", {
        "name": "training_floor", "type": "plane", "size": "0 0 0.05",
        "pos": "0 0 0", "material": "groundplane",
        "contype": "1", "conaffinity": "2",
    }))
    ET.indent(root, space="  ")
    return (ET.tostring(root, encoding="unicode") + "\n").encode("utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="compare regenerated bytes with checked-in scene")
    args = parser.parse_args()
    generated = generate()
    if args.check:
        if OUTPUT.read_bytes() != generated:
            raise SystemExit("scene differs from generator output")
        print(f"scene matches generator: {OUTPUT.relative_to(ROOT)}")
    else:
        OUTPUT.write_bytes(generated)
        print(f"wrote {OUTPUT.relative_to(ROOT)} ({len(generated)} bytes)")


if __name__ == "__main__":
    main()
